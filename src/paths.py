"""Два корня приложения: где лежат **ресурсы сборки** и где лежит **рабочая база**.

До наряда `0040` корень был один и считался от исходников. Под однофайловой
сборкой PyInstaller это ломается тихо и полностью: `sys._MEIPASS` — каталог
распаковки, он создаётся при старте и **стирается при выходе**. База, заведённая
там, исчезает вместе с ним, и оператор теряет всё, что ввёл, не увидев ни одного
сообщения об ошибке.

**Почему две функции, а не одна с флагом.** Вне заморозки они возвращают одно и
то же и различить их негде; расходятся они ровно внутри заморозки — то есть в
единственном режиме, где ошибка проявляется, и в том, где её труднее всего
заметить. Разные имена не дают перепутать их в вызове.

**Признак заморозки — `sys.frozen`**, а не наличие `_MEIPASS` и не разбор
`sys.argv[0]`: наблюдать надо нужную величину, а не её удобный признак
(`CLAUDE.md` §9а.24). `_MEIPASS` при этом читается **внутри** ветки заморозки —
он и есть каталог распаковки, — но вопрос «заморожены ли мы» задаётся тому, кто
на него отвечает.

Обе — **чистые функции без побочных действий** и читают `sys` в момент вызова,
а не при импорте: свойство, которое нельзя показать сравнением «до/после» на
живой сборке, выносится в чистую функцию и проверяется арифметикой
(`CLAUDE.md` §9а.14, Д-3 наряда `0040`).
"""

from __future__ import annotations

import sys
from pathlib import Path

#: Корень репозитория: `src/paths.py` → `src` → репо. Значение только для
#: незамороженного запуска; под сборкой исходников на диске нет вовсе.
REPO_ROOT = Path(__file__).resolve().parents[1]


def frozen() -> bool:
    """Запущены ли мы из упакованной сборки."""
    return bool(getattr(sys, "frozen", False))


def data_root() -> Path:
    """Где лежат **ресурсы сборки**: `alembic.ini`, `migrations/`.

    Под заморозкой — каталог распаковки (`sys._MEIPASS`): туда PyInstaller
    кладёт всё, что перечислено данными. Каталог **временный**, и это верно:
    ресурсы читаются, но не переживают запуск, потому что их источник — сама
    сборка.

    Запасной путь при `frozen()` без `_MEIPASS` — папка исполняемого файла: так
    ведёт себя однопапочная (`onedir`) сборка, где распаковывать нечего.
    """
    if frozen():
        unpacked = getattr(sys, "_MEIPASS", None)
        if unpacked:
            return Path(unpacked)
        return Path(sys.executable).resolve().parent
    return REPO_ROOT


def work_root() -> Path:
    """Где лежит **рабочий файл базы** — рядом с `.exe`.

    Решение пользователя 2026-09-10. Правило «бэкап = копия одного файла»
    (`architecture.md` §3) при этом остаётся буквально верным: оператор видит
    файл глазами рядом с программой и копирует его мышью.

    Следствие для поставки: `.exe` кладётся в обычную рабочую папку, **не** в
    `Program Files` — туда Windows писать не даст, и база не создастся.
    Перекрыть расположение по-прежнему можно переменной `QMS_DB_URL`.
    """
    if frozen():
        return Path(sys.executable).resolve().parent
    return REPO_ROOT
