"""Непечатаемое ячейки и правило подсказки — **замером**, в одном месте.

Два вопроса, у которых один ответ, и потому один модуль:

* сколько пикселей колонки **не достаётся** тексту (нужно, чтобы назначить
  ширину);
* влезло ли нарисованное в то, что осталось (нужно, чтобы поставить подсказку).

Числа берутся у самого стиля, а не вписываются: они зависят от листа стиля,
платформы и масштаба, и зашитая константа врала бы на соседней машине молча —
ровно тот отказ, из-за которого `Q-09` в своё время перевели с ручного `rev` на
хеш.

**Зазоров три, и это не педантизм — каждый принадлежит своему рисующему.**

* `delegate_chrome` — **21**: отступы ячейки (`PAD_CELL * 2`) плюс линия сетки.
  Столько теряет делегат, который рисует ячейку **сам** (пилюля исхода, пилюли
  находок): он получает `option.rect` и распоряжается им целиком.
* `cell_chrome` — **27**: то же плюс `2 * (PM_FocusFrameHMargin + 1)`. Столько
  теряет **текст**, который рисует стиль: `QCommonStyle` при отрисовке
  `CE_ItemViewItem` вычитает этот отступ внутри себя, и в `SE_ItemViewItemText`
  его не видно.
* `header_chrome` — **20**: у заголовка своё, и добавочного отступа текста у него
  нет вовсе (`CE_HeaderLabel` рисует в выданный прямоугольник).

**Как эти числа проверены — и почему не тем способом, каким казалось.**
Первый заход наряда `0034` снял зазор через `subElementRect(SE_ItemViewItemText)`
и получил 21, объявив шесть пикселей лишними. Опроверг это **снимок**: `Abutment`
(56 px) в колонке 77 px резался до `Abutm…`, а `Implant` (43 px) — нет. По 21
обрезки не было бы ни в одном случае, по 27 — ровно в наблюдаемом. То же на
историческом наблюдении наряда `0028`: `W26007336` (68) в колонке 92 резался, в
100 — нет. Четыре случая из четырёх ложатся на 27 и ни один на 21.

Отсюда правило, которое стоило целого захода: **`subElementRect` отвечает, куда
стиль кладёт текст, а не по какой ширине он его режет** — это разные величины, и
вторая живёт внутри `drawControl`. Арбитр — отрисовка (`CLAUDE.md` §9а.25), и
именно поэтому проверка ширины обязана кончаться снимком, а не замером.
"""

from __future__ import annotations

from PySide6.QtCore import QEvent, QRect, Qt
from PySide6.QtWidgets import (
    QStyle,
    QStyleOptionHeader,
    QStyleOptionViewItem,
    QToolTip,
)

from . import tokens as t

#: Ширина пробного прямоугольника, на котором снимается зазор. Величина
#: произвольная и на ответ не влияет: вычитается разность, а не доля. Взята
#: заведомо больше любого мыслимого непечатаемого, чтобы `subElementRect` не
#: упёрся в ноль и не вернул усечённый результат.
_PROBE_WIDTH = 400
_PROBE_HEIGHT = 32

#: Высота, означающая «сколько понадобится» при замере переноса.
_UNBOUNDED = 1 << 20

#: Роль «подсказка **содержательная** — показывать всегда, а не по обрезке».
#:
#: Объявленное исключение из правила §4 наряда `0034`, и другого способа его
#: выразить нет: обычная `ToolTipRole` показывается только когда нарисованное не
#: влезло, а сводка обязана быть видна и тогда, когда влезло. Повод — колонка
#: `Inspections` в таблице находок (§2 наряда `0035`): она показывает тип первой
#: записи и `+N`, и подсказка перечисляет **все** — показать одну и умолчать про
#: остальные значило бы соврать оператору.
#:
#: Роль, а не второй механизм: ставит её экран, читает то же единственное место,
#: что и подсказку по обрезке. Следующий наряд, увидев подсказку на неурезанной
#: ячейке, найдёт здесь основание и не «починит» её обратно.
CONTENT_TOOLTIP_ROLE = Qt.ItemDataRole.UserRole + 6


def delegate_chrome(view) -> int:
    """Что теряет делегат, рисующий ячейку **сам**: отступы ячейки и линия сетки.

    Оба слагаемых измеряются, а не назначаются:

    * отступы — разность между прямоугольником ячейки и тем, куда стиль кладёт
      текст (`SE_ItemViewItemText`); под листом стиля канона это `PAD_CELL * 2`;
    * линия сетки — колонка отдаёт её соседу, и распоряжаться этой полосой не
      может никто. Слагаемое появляется только при включённой сетке (`showGrid`).

    Это бюджет пилюли исхода и пилюль находок: они получают `option.rect` и
    рисуют в нём своими руками, добавочного отступа текста стиля не платя.
    """
    # **Сначала довести виджет до применённого стиля.** Отступы ячейки приходят
    # из листа стиля, а лист резолвится при `polish`, не при создании: у
    # непричёсанного виджета `subElementRect` возвращает прямоугольник без
    # отступов, и замер даёт 1 вместо 21. Ширины назначаются как раз при сборке
    # таблицы — то есть ровно в ту минуту, когда замер ещё не готов отвечать.
    view.ensurePolished()
    option = QStyleOptionViewItem()
    option.initFrom(view)
    option.rect = QRect(0, 0, _PROBE_WIDTH, _PROBE_HEIGHT)
    text = view.style().subElementRect(
        QStyle.SubElement.SE_ItemViewItemText, option, view
    )
    padding = _PROBE_WIDTH - text.width()
    grid = t.BORDER_WIDTH if view.showGrid() else 0
    return padding + grid


def text_margin(view) -> int:
    """Добавочный отступ, который стиль вычитает **при отрисовке текста**.

    `QCommonStyle::viewItemDrawText` отступает от текстового прямоугольника ещё
    `PM_FocusFrameHMargin + 1` с каждой стороны. В `subElementRect` этого не
    видно — там лежит прямоугольник, **куда** кладут текст, а не ширина, **по
    которой** его режут. Величины разные, и путать их дорого: на этой разнице
    первый заход наряда `0034` объявил шесть пикселей лишними, а снимок показал
    обратное (см. шапку модуля).
    """
    return 2 * (
        view.style().pixelMetric(
            QStyle.PixelMetric.PM_FocusFrameHMargin, QStyleOptionViewItem(), view
        )
        + 1
    )


def cell_chrome(view) -> int:
    """Сколько пикселей колонки не достаётся **тексту**, который рисует стиль.

    `delegate_chrome` плюс добавочный отступ отрисовки: 27 на рабочей машине
    (20 + 1 + 6). Именно это число и назначает ширину текстовой колонки — оно
    же решает, поставить ли подсказку по обрезке.
    """
    return delegate_chrome(view) + text_margin(view)


def header_chrome(view) -> int:
    """То же для **заголовка**, и число у него своё.

    Линия сетки сюда не входит: `SE_HeaderLabel` её не вычитает, поэтому
    заголовку хватает одних отступов — 20 против 21 у ячейки. Разница в один
    пиксель не педантизм: колонка класса «по заголовку» (`FIT_LABEL`) назначается
    именно этим числом, и лишний пиксель на каждой такой колонке сдвигает
    объявленную сумму таблицы (`card_dialog.PRECEDENT_WIDTHS` — 1119 при полотне
    1120, запас ровно один пиксель).
    """
    header = view.horizontalHeader()
    header.ensurePolished()
    option = QStyleOptionHeader()
    header.initStyleOption(option)
    option.rect = QRect(0, 0, _PROBE_WIDTH, _PROBE_HEIGHT)
    label = header.style().subElementRect(
        QStyle.SubElement.SE_HeaderLabel, option, header
    )
    return _PROBE_WIDTH - label.width()


def frame_height(view) -> int:
    """Сколько высоты виджета не достаётся полотну — **рамка сверху и снизу**.

    Вертикальный член той же семьи, что зазоры ширины выше, и заведён по тому же
    поводу: **объявленная высота не есть нарисованная** (`CLAUDE.md` §9а.12,
    вертикальный случай). Лист стиля даёт таблице `border: 1px`, и полотну
    достаётся на два пикселя меньше заданной высоты. Последняя строка не влезает
    ровно на эти два, и Qt рисует полосу прокрутки там, где прокручивать нечего:
    полоса обещает содержимое ниже, оператор тянет её и возвращается ни с чем.
    Замерено на всех четырёх таблицах карточки и списка (наряд `0036` §0).

    **Считается по `contentsMargins`, а не по `frameWidth()`** — и это не вкус.
    `frameWidth()` у этих таблиц включает **горизонтальный** отступ полотна,
    которым центрируется сетка (`_centre_columns` задаёт его листом стиля, а Qt
    относит к рамке — см. `centring_margin`). Замерено: на таблице находок
    карточки `frameWidth() * 2` даёт **240** при истинных **2**. Взяв её,
    высота выросла бы на четверть экрана и дефект сменился бы на противоположный.
    """
    margins = view.contentsMargins()
    return margins.top() + margins.bottom()


def room_for_text(view, column: int) -> int:
    """Сколько ширины остаётся тексту в этой колонке — то, с чем сверяется замер.

    Единственное место, где ширина колонки превращается в доступную ширину
    текста. Раньше это выражение было переписано в каждом делегате своей
    константой (`columnWidth - PAD_CELL * 2`) — то есть каждый делегат ошибался
    на своё, и ни один не совпадал со стилем.
    """
    return max(view.columnWidth(column) - cell_chrome(view), 0)


def room_for_delegate(view, column: int) -> int:
    """То же для делегата, рисующего ячейку сам: бюджет у него на 6 px шире."""
    return max(view.columnWidth(column) - delegate_chrome(view), 0)


def text_height(view, row: int) -> int:
    """Сколько высоты строки достаётся тексту — замером у стиля, как и ширина.

    Нужно там, где ячейка **переносит**: у такой строка не режется по ширине, и
    вопрос «влезло ли» становится вопросом о высоте.
    """
    view.ensurePolished()
    option = QStyleOptionViewItem()
    option.initFrom(view)
    option.rect = QRect(0, 0, _PROBE_WIDTH, view.rowHeight(row))
    text = view.style().subElementRect(
        QStyle.SubElement.SE_ItemViewItemText, option, view
    )
    return max(text.height(), 0)


class TruncationTooltip:
    """Подсказка тогда и только тогда, когда **нарисованное** не влезло.

    Примесь к делегату, а не свободная функция: спросить «а какой ширины то, что
    ты рисуешь» можно только у того, кто рисует. Делегат текста отвечает шириной
    строки, делегат пилюли — шириной пилюли с оправой и **своим** кеглем, делегат
    находок — шириной самой широкой пилюли столбика. Замер по строке ячейки для
    двух последних не годится: рисуют они не строку и не тем шрифтом (`CLAUDE.md`
    §9а.24 — наблюдать величину, а не её удобный признак).

    **Порог по счёту снят.** До наряда `0034` подсказка у находок стояла при
    `len(chips) > CHIPS_SHOWN`, а у обоснования — безусловно: то есть молчала там,
    где текст обрезан, и появлялась там, где всё поместилось. Счёт остаётся
    условием строки «+N findings» и только им.

    **`ToolTipRole` снова доходит до экрана.** Прежний `helpEvent` возвращал
    `True` на любое событие подсказки и показывал `DisplayRole`, поэтому
    `setToolTip` на экранах не показывался **никогда** — подтверждено пробой
    (наряд `0034`). Здесь роль читается первой: экран, положивший в неё полный
    текст с переносами, получает его, а не однострочную выжимку из ячейки.
    """

    def drawn_width(self, option, index) -> int:
        """Ширина того, что делегат нарисует. Переопределяется рисующими.

        База — обычный текст ячейки в шрифте вида.
        """
        text = index.data() or ""
        return option.fontMetrics.horizontalAdvance(str(text))

    def available_width(self, view, index) -> int:
        """Сколько ширины делегату досталось. Переопределяется теми, кто считает
        её иначе, **чем стиль**.

        Умолчание — `room_for_text`. Делегат находок отсчитывает свой предел от
        `option.rect.right()`, а это на пиксель левее правого края (правый край
        прямоугольника — `left + width - 1`), поэтому у него бюджет на линию
        сетки меньше. Расхождение мелкое, но переопределять его надо здесь, а не
        подгонять слагаемым в `drawn_width`: там оно перестало бы читаться.
        """
        return room_for_text(view, index.column())

    def tooltip_text(self, index) -> str:
        """Что показать: роль подсказки, если экран её задал, иначе — значение."""
        from PySide6.QtCore import Qt  # noqa: PLC0415 — иначе круговой импорт

        role = index.data(Qt.ItemDataRole.ToolTipRole)
        return str(role if role else (index.data() or ""))

    def truncated(self, view, option, index) -> bool:
        """Не влезло ли нарисованное. Одно выражение на все таблицы.

        **Там, где ячейка переносит, ширина перестаёт быть ответом.** Список
        отклонений включает перенос на колонке обоснования осознанно (наряд
        `0028`: в одну строку реальное обоснование не влезает ни при какой
        ширине). У такой ячейки текст, не поместившийся в строку, уходит на
        вторую, а не за край, — и подсказка по одной только ширине встала бы
        почти всегда, то есть осталась бы той самой безусловной подсказкой,
        которую §4 наряда `0034` и снимает. Поэтому при переносе спрашивается
        **высота**: влез ли текст в отведённые строке пиксели.
        """
        room = self.available_width(view, index)
        if self.drawn_width(option, index) <= room:
            return False
        if not (room and getattr(view, "wordWrap", None) and view.wordWrap()):
            return True

        text = str(index.data() or "")
        bounds = option.fontMetrics.boundingRect(
            QRect(0, 0, room, _UNBOUNDED),
            int(Qt.TextFlag.TextWordWrap),
            text,
        )
        return bounds.height() > text_height(view, index.row())

    def style_option(self, view, option, index) -> QStyleOptionViewItem:
        """Заполненный `option` — **свой**, если переданному нельзя доверять.

        Зовущий не обязан его дать: у `QTableWidget` в PySide6 нет `viewOptions`
        (метод защищённый), и тест, который его ищет, передаёт сюда `None`.
        Обращение к `None` на границе Python ↔ C++ роняет **процесс**, а не тест:
        access violation без питоновской трассы, и весь прогон встаёт (`CLAUDE.md`
        §9а.14 — тот же класс, что стоп-дефект наряда `0028`).

        Поэтому option здесь не принимается на веру, а проверяется по типу.
        """
        if not isinstance(option, QStyleOptionViewItem):
            option = QStyleOptionViewItem()
            option.initFrom(view)
        self.initStyleOption(option, index)
        return option

    def helpEvent(self, event, view, option, index) -> bool:  # noqa: N802 — имя от Qt
        if event.type() != QEvent.Type.ToolTip or not index.isValid():
            return super().helpEvent(event, view, option, index)

        # Содержательная сводка показывается **всегда** — она не компенсирует
        # обрезку, а несёт то, чего в ячейке нет (`CONTENT_TOOLTIP_ROLE`).
        content = index.data(CONTENT_TOOLTIP_ROLE)
        if content:
            QToolTip.showText(event.globalPos(), str(content), view)
            return True

        option = self.style_option(view, option, index)
        text = self.tooltip_text(index)
        if text and self.truncated(view, option, index):
            QToolTip.showText(event.globalPos(), text, view)
        else:
            QToolTip.hideText()
        return True
